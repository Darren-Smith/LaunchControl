#!/usr/bin/env python3
"""Find unreferenced assets in LaunchControlDist/games/* and write asset_audit.md.

A non-code file is "referenced" if its file name (or path tail) appears in any code
file of the same game. Files whose names look dynamically built (e.g. walk_3.png when
code contains "walk_") are flagged SUSPECT and are never auto-deleted.

Usage:
  scripts/audit_assets.py                 -> writes asset_audit.md (no changes)
  scripts/audit_assets.py --apply FILE    -> deletes paths listed in FILE (one per line,
                                             relative to games/), e.g. an edited copy of
                                             the "UNUSED" lists from the report.
"""
import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GAMES = ROOT / "games"
CODE_EXT = {".html", ".htm", ".js", ".mjs", ".css", ".py", ".json", ".txt", ".svg"}
SAVE_HINTS = ("leaderboard", "highscore", "scores", "save")


def human(n):
    return f"{n/1e6:.2f} MB" if n >= 1e5 else f"{n/1e3:.0f} KB"


def audit_game(gdir: Path):
    files = [f for f in gdir.rglob("*") if f.is_file()]
    code = [f for f in files if f.suffix.lower() in CODE_EXT]
    blob = "\n".join(f.read_text(errors="ignore") for f in code)
    blob_l = blob.lower()

    used, unused, suspect, saves = [], [], [], []
    for f in files:
        rel = f.relative_to(gdir)
        if f.suffix.lower() in CODE_EXT:
            if f.suffix.lower() == ".json" and any(h in f.name.lower() for h in SAVE_HINTS):
                saves.append(rel)
            continue
        name = f.name.lower()
        if name in blob_l or f.stem.lower() in blob_l and len(f.stem) > 3:
            used.append(rel)
            continue
        # dynamic-name heuristic: strip trailing digits/separators -> prefix in code?
        m = re.match(r"^(.*?)[_\-\s]?\d+$", f.stem)
        prefix = m.group(1).lower() if m else ""
        if prefix and len(prefix) >= 3 and prefix in blob_l:
            suspect.append(rel)
        elif f.parent != gdir and f.parent.name.lower() in blob_l and \
                re.search(re.escape(f.parent.name.lower()) + r"/['\"`]?\s*\+|\$\{", blob_l):
            suspect.append(rel)
        else:
            unused.append(rel)
    size = lambda lst: sum((gdir / r).stat().st_size for r in lst)
    return dict(total=size([f.relative_to(gdir) for f in files]), used=used,
                unused=unused, suspect=suspect, saves=saves, size=size)


def write_report():
    out = ["# Asset Audit\n",
           "Generated by `scripts/audit_assets.py`. Nothing has been deleted.\n",
           "- **UNUSED**: file name not found anywhere in the game's code → safe to delete candidates.",
           "- **SUSPECT**: name looks dynamically built (e.g. `frame_3.png`) → check before deleting.",
           "- **SAVE FILES**: runtime data written by the game → will move to the user data dir in Phase 1.\n"]
    summary = []
    grand_unused = 0
    details = []
    for g in sorted(p for p in GAMES.iterdir() if p.is_dir()):
        r = audit_game(g)
        su, ss = r["size"](r["unused"]), r["size"](r["suspect"])
        grand_unused += su
        summary.append(f"| {g.name} | {human(r['total'])} | {len(r['unused'])} / {human(su)} | "
                       f"{len(r['suspect'])} / {human(ss)} | {', '.join(map(str, r['saves'])) or '–'} |")
        if r["unused"] or r["suspect"]:
            details.append(f"\n## {g.name}\n")
            for label, lst in (("UNUSED", r["unused"]), ("SUSPECT", r["suspect"])):
                if lst:
                    details.append(f"**{label}**\n")
                    for rel in sorted(lst):
                        details.append(f"- [ ] `{g.name}/{rel}` ({human((g / rel).stat().st_size)})")
                    details.append("")
    out += ["| Game | Size | Unused (n / size) | Suspect | Save files |", "|---|---|---|---|---|"]
    out += summary
    out.append(f"\n**Potential saving from UNUSED: {human(grand_unused)}**")
    out += details
    (ROOT / "asset_audit.md").write_text("\n".join(out) + "\n")
    print(f"Wrote {ROOT / 'asset_audit.md'}  (unused total {human(grand_unused)})")


def apply(listfile: Path):
    n = 0
    for line in listfile.read_text().splitlines():
        m = re.search(r"`([^`]+)`", line) if "`" in line else None
        p = (m.group(1) if m else line).strip()
        if not p or p.startswith("#"):
            continue
        target = (GAMES / p).resolve()
        if GAMES.resolve() not in target.parents or not target.is_file():
            print(f"skip {p}", file=sys.stderr)
            continue
        target.unlink()
        n += 1
        print(f"deleted games/{p}")
    print(f"{n} files deleted")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", type=Path)
    a = ap.parse_args()
    apply(a.apply) if a.apply else write_report()
